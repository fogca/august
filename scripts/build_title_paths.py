#!/usr/bin/env python3
"""Draws each typeface page's big name as outlines, for the opening path animation.

    python3 scripts/build_title_paths.py

2026-11-20, at the user's request, after nguyengobber.com/typefaces/sticks
("参考サイトのように、path animationから始めて欲しい"): the typeface page opens
with the name's outlines drawn as thin lines, then filled. The page needs the
outlines as SVG paths, so this sets each name in its own face, at the weight the
page shows it in, with HarfBuzz (kerning on), and writes
src/lib/data/titlePaths.ts: per typeface, one entry whose viewBox is the INK
box of the name (so "90% wide" is the letters themselves, not their side
bearings, and the name centres on its ink), and per letter the whole outline
(for the fill) and its contours one by one (for the stroke that draws itself —
a counter must not be filled by a contour's own path, so the two are separate).

A typeface without an entry here keeps the plain text title (fitText).
Run it again when a font file or the weight a name is shown at changes.

Needs fontTools, brotli, uharfbuzz and skia-pathops.
"""

from __future__ import annotations

import io
import re
from pathlib import Path

import pathops
import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/lib/data/titlePaths.ts"

# slug, font file, wght (None: not a variable font), the text as the page sets it
# (see displayNameAsSet() and the page's titleWeight in fonts/[slug]/+page.svelte).
TITLES = [
    ("pf-humorist", "static/fonts/Ango-VF47.woff2", 450, "HUMORIST"),
    ("pf-maxa", "static/fonts/Maxica-VF38.woff2", 500, "Maxa"),
    ("pf-gigi-sans", "static/fonts/GigiSans-VF06.woff2", 400, "Gigi Sans"),
]

DECIMALS = 1


def r(value: float) -> float:
    return round(value, DECIMALS)


def load(path: str, wght: int | None) -> TTFont:
    font = TTFont(ROOT / path)
    if wght is not None:
        font = instancer.instantiateVariableFont(font, {"wght": wght})
    return font


def shape(font: TTFont, text: str) -> list[tuple[str, float]]:
    """(character, x of its origin), kerning applied."""
    buf = io.BytesIO()
    font.flavor = None  # HarfBuzz reads a bare sfnt, not the woff2
    font.save(buf)
    hb_font = hb.Font(hb.Face(buf.getvalue()))
    run = hb.Buffer()
    run.add_str(text)
    run.guess_segment_properties()
    hb.shape(hb_font, run)
    x = 0.0
    out = []
    for info, pos in zip(run.glyph_infos, run.glyph_positions):
        out.append((text[info.cluster], x + pos.x_offset))
        x += pos.x_advance
    return out


def glyph_name(font: TTFont, char: str) -> str:
    return font.getBestCmap()[ord(char)]


def build_one(slug: str, path: str, wght: int | None, text: str) -> str:
    font = load(path, wght)
    glyphs = font.getGlyphSet()
    placed = [(ch, x) for ch, x in shape(font, text) if ch != " "]

    # The ink box, in font units (y up).
    xs0, xs1, ys0, ys1 = [], [], [], []
    for ch, x in placed:
        bp = BoundsPen(glyphs)
        glyphs[glyph_name(font, ch)].draw(bp)
        gx0, gy0, gx1, gy1 = bp.bounds
        xs0.append(x + gx0)
        xs1.append(x + gx1)
        ys0.append(gy0)
        ys1.append(gy1)
    min_x, max_x, min_y, max_y = min(xs0), max(xs1), min(ys0), max(ys1)
    width, height = max_x - min_x, max_y - min_y

    letters = []
    for ch, x in placed:
        # y down, the ink box's top-left at the origin. Overlaps are merged first:
        # a variable font's letters are often several overlapping contours (the
        # bar and the stems of an H), and the stroke would draw each one's edge
        # inside the letter.
        merged = pathops.Path()
        glyphs[glyph_name(font, ch)].draw(
            TransformPen(merged.getPen(glyphSet=glyphs), (1, 0, 0, -1, x - min_x, max_y))
        )
        merged.simplify(fix_winding=True, keep_starting_points=False)
        pen = SVGPathPen(glyphs, ntos=lambda v: f"{r(v):g}")
        merged.draw(pen)
        d = pen.getCommands()
        contours = [c for c in re.split(r"(?=M)", d) if c]
        letters.append((ch, d, contours))

    lines = [f"\t'{slug}': {{", f"\t\twidth: {r(width):g},", f"\t\theight: {r(height):g},", "\t\tletters: ["]
    for ch, d, contours in letters:
        joined = ", ".join(f"'{c}'" for c in contours)
        lines.append(f"\t\t\t{{ char: '{ch}', d: '{d}', contours: [{joined}] }},")
    lines.append("\t\t]")
    lines.append("\t}")
    return "\n".join(lines)


def main() -> None:
    body = ",\n".join(build_one(*t) for t in TITLES)
    OUT.write_text(
        "// GENERATED by scripts/build_title_paths.py — edit that, not this.\n"
        "//\n"
        "// Each typeface page's big name as outlines (see the script), for the path\n"
        "// animation the page opens with. width / height: the name's ink box, in font\n"
        "// units (the SVG's viewBox is 0 0 width height); a letter's `d` is the whole\n"
        "// outline (the fill), `contours` its sub-paths one by one (the strokes).\n\n"
        "export interface TitleLetter {\n\tchar: string;\n\td: string;\n\tcontours: string[];\n}\n\n"
        "export interface TitlePath {\n\twidth: number;\n\theight: number;\n\tletters: TitleLetter[];\n}\n\n"
        "export const TITLE_PATHS: Record<string, TitlePath> = {\n" + body + "\n};\n"
    )
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
