#!/usr/bin/env python3
"""Sets the site's wordmark in a face of ours and writes it out as outlines.

    python3 scripts/build_wordmark.py

Reads static/fonts/Maxica-VF18.woff2, pins it to one weight, shapes WORDMARK_TEXT
with HarfBuzz (kerning on) and writes src/lib/data/wordmark.ts: one SVG path per
letter, in one coordinate space, y down, the baseline at CAP + PAD. Logo.svelte
draws them the way it drew the old artwork's paths, so the opening's letter-by-
letter rise and the Header's shrink into its compact lockup work unchanged, and
the Header needs no web font to show its mark.

Needs fontTools, brotli and uharfbuzz. To change the name, the face or the
weight, edit the constants below and run it again.
"""

import io
import math
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "static/fonts/Maxica-VF18.woff2"
OUT = ROOT / "src/lib/data/wordmark.ts"

# 2026-11-05, at the user's request: "Texmex Typefoundry Tokyo" for now, in
# Maxa Regular, capitalised (initial capitals; first set in all caps by
# mistake, then corrected). Maxica draws A-Z and a-y, so the name has to stay
# clear of "z".
WORDMARK_TEXT = "Texmex Typefoundry Tokyo"
WEIGHT = 400
# Where the name breaks into the two words the Header moves (the first word's
# letters, then the rest — a space inside the second word stays a space).
FIRST_WORD = "Texmex"

# Room above the tallest ink and below the lowest, in font units: the box is
# measured off the letters themselves (ascenders d f k, descenders y p).
PAD = 4

DECIMALS = 2


def r(value: float) -> float:
    return round(value, DECIMALS)


def pinned_font() -> TTFont:
    font = TTFont(FONT)
    return instancer.instantiateVariableFont(font, {"wght": WEIGHT})


def shaped_positions(font: TTFont) -> tuple[list[tuple[str, float]], float]:
    """(character, x of its origin) for every character, kerning applied, and
    the line's total advance."""
    buf = io.BytesIO()
    font.flavor = None  # HarfBuzz reads a bare sfnt, not the woff2 the file was
    font.save(buf)
    face = hb.Face(buf.getvalue())
    hb_font = hb.Font(face)
    run = hb.Buffer()
    run.add_str(WORDMARK_TEXT)
    run.guess_segment_properties()
    hb.shape(hb_font, run)
    x = 0.0
    out = []
    for info, pos in zip(run.glyph_infos, run.glyph_positions):
        out.append((WORDMARK_TEXT[info.cluster], x + pos.x_offset))
        x += pos.x_advance
    return out, x


def glyph_bounds(font: TTFont, char: str) -> tuple[float, float, float, float]:
    glyph_set = font.getGlyphSet()
    bp = BoundsPen(glyph_set)
    glyph_set[font.getBestCmap()[ord(char)]].draw(bp)
    return bp.bounds


def outline(
    font: TTFont, char: str, x: float, baseline: float
) -> tuple[str, float, float]:
    """The letter's path in wordmark space and its horizontal extent."""
    glyph_set = font.getGlyphSet()
    name = font.getBestCmap()[ord(char)]
    pen = SVGPathPen(glyph_set, ntos=lambda v: f"{r(v):g}")
    glyph_set[name].draw(TransformPen(pen, (1, 0, 0, -1, x, baseline)))
    x0, _, x1, _ = glyph_bounds(font, char)
    return pen.getCommands(), r(x + x0), r(x + x1)


def build() -> str:
    font = pinned_font()
    assert font["head"].unitsPerEm == 1000, "the numbers below are in 1000-unit em"
    placed, total = shaped_positions(font)

    # The box: from the top of the tallest letter to the foot of the lowest.
    ink = [glyph_bounds(font, ch) for ch, _ in placed if ch != " "]
    ascent = math.ceil(max(b[3] for b in ink)) + PAD
    descent = math.ceil(-min(b[1] for b in ink)) + PAD
    baseline, height = ascent, ascent + descent

    letters = []
    origins = {}
    for i, (char, x) in enumerate(placed):
        origins[i] = x
        if char == " ":
            continue
        d, x0, x1 = outline(font, char, x, baseline)
        letters.append({"char": char, "x0": x0, "x1": x1, "d": d, "index": i})

    first_end = len(FIRST_WORD)
    gap_end = first_end + 1  # the space after the first word
    n_first = sum(1 for lt in letters if lt["index"] < first_end)
    words = [
        {"text": FIRST_WORD, "from": 0, "to": n_first, "x0": 0, "x1": r(origins[first_end])},
        {
            "text": WORDMARK_TEXT[gap_end:],
            "from": n_first,
            "to": len(letters),
            "x0": r(origins[gap_end]),
            "x1": r(total),
        },
    ]

    lines = [
        "// GENERATED by scripts/build_wordmark.py — edit that, not this.",
        "//",
        f"// The wordmark \"{WORDMARK_TEXT}\" in Maxica-VF18 at wght {WEIGHT} (Maxa Regular),",
        "// one outline per letter in one coordinate space (y down, em = 1000 units).",
        "// Logo.svelte draws it; $lib/data/logo.ts turns its proportions into the CSS",
        "// custom properties the Header's lockup and the masthead are laid out from.",
        "",
        f"export const WORDMARK_TEXT = {WORDMARK_TEXT!r};",
        f"export const WORDMARK_W = {r(total)};",
        f"export const WORDMARK_H = {height};",
        "",
        "export interface WordmarkLetter {",
        "\tchar: string;",
        "\tx0: number;",
        "\tx1: number;",
        "\td: string;",
        "}",
        "",
        "/** The two words the Header moves: the letters from..to of WORDMARK_LETTERS,",
        " *  and the x range of the wordmark they stand on. */",
        "export const WORDMARK_WORDS = [",
    ]
    for w in words:
        lines.append(
            f"\t{{ text: {w['text']!r}, from: {w['from']}, to: {w['to']}, x0: {w['x0']}, x1: {w['x1']} }},"
        )
    lines[-1] = lines[-1].rstrip(",")
    lines += ["] as const;", "", "export const WORDMARK_LETTERS: WordmarkLetter[] = ["]
    for i, lt in enumerate(letters):
        comma = "," if i < len(letters) - 1 else ""
        lines.append(
            f"\t{{ char: {lt['char']!r}, x0: {lt['x0']}, x1: {lt['x1']}, d: {lt['d']!r} }}{comma}"
        )
    lines.append("];")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.write_text(build())
    print(f"wrote {OUT.relative_to(ROOT)}")
