#!/usr/bin/env python3
"""Draws the site's icons and share image, in black and white, from our own faces.

    python3 scripts/build_icons.py

2026-11-11, at the user's request (the move to timetokyo.pages.dev — "metaや
faviconまでしっかり白黒デザインでTなど使って"):

- Icons: the T of Maxa (Maxica-VF35, SemiBold) in white on black. One SVG
  (static/favicon.svg) and the PNGs browsers and home screens ask for —
  favicon.png 512, apple-touch-icon.png 180, icon-192.png, icon-512.png (also
  the PWA's maskable icon: the T sits well inside its 80% safe circle).
- Share image (static/og.png, 1200x630): the wordmark, as the Header draws it
  ($lib/data/wordmark.ts), in white on black.

Needs fontTools and brotli; the PNGs are rasterised with sharp (a dependency
of the site already) through Node.
"""

import json
import re
import subprocess
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
STATIC = ROOT / "static"
FONT = ROOT / "scripts/fonts/Maxica-VF35.woff2"
WORDMARK_TS = ROOT / "src/lib/data/wordmark.ts"

BLACK = "#000000"
WHITE = "#ffffff"

# Icon
ICON_SIZE = 512
ICON_LETTER = "T"
ICON_WEIGHT = 650  # SemiBold: Regular's stem goes to a hairline at 16px
ICON_LETTER_HEIGHT = 0.56  # cap height as a share of the icon

# Share image
OG_W, OG_H = 1200, 630
OG_MARGIN = 56

PNG_SIZES = {
    "favicon.png": 512,
    "apple-touch-icon.png": 180,
    "icon-192.png": 192,
    "icon-512.png": 512,
}


def icon_svg() -> str:
    font = instancer.instantiateVariableFont(TTFont(FONT), {"wght": ICON_WEIGHT})
    glyphs = font.getGlyphSet()
    glyph = glyphs[font.getBestCmap()[ord(ICON_LETTER)]]
    bounds = BoundsPen(glyphs)
    glyph.draw(bounds)
    x0, y0, x1, y1 = bounds.bounds
    height = ICON_SIZE * ICON_LETTER_HEIGHT
    k = height / (y1 - y0)
    tx = (ICON_SIZE - (x1 - x0) * k) / 2 - x0 * k
    ty = (ICON_SIZE + height) / 2 + y0 * k
    pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    glyph.draw(TransformPen(pen, (k, 0, 0, -k, tx, ty)))
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {ICON_SIZE} {ICON_SIZE}">\n'
        f"\t<!-- The T of TTT Maxa (SemiBold), white on black. Generated by\n"
        f"\t     scripts/build_icons.py. -->\n"
        f'\t<rect width="{ICON_SIZE}" height="{ICON_SIZE}" fill="{BLACK}" />\n'
        f'\t<path fill="{WHITE}" d="{pen.getCommands()}" />\n'
        f"</svg>\n"
    )


def og_svg() -> str:
    source = WORDMARK_TS.read_text()
    width = float(re.search(r"WORDMARK_W = ([\d.]+)", source).group(1))
    paths = re.findall(r"d: '([^']+)'", source)
    k = (OG_W - 2 * OG_MARGIN) / width
    body = "".join(f'<path d="{d}" />' for d in paths)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {OG_W} {OG_H}">'
        f'<rect width="{OG_W}" height="{OG_H}" fill="{BLACK}" />'
        f'<g fill="{WHITE}" transform="translate({OG_MARGIN} {OG_MARGIN}) scale({k:.6f})">{body}</g>'
        f"</svg>"
    )


def rasterise(jobs: list[tuple[str, str, int, int]]) -> None:
    """jobs: (svg text, output path, width, height), drawn by sharp."""
    script = """
const sharp = require('sharp');
const jobs = JSON.parse(require('fs').readFileSync(0, 'utf8'));
(async () => {
  for (const [svg, out, w, h] of jobs) {
    await sharp(Buffer.from(svg), { density: 300 }).resize(w, h).flatten({ background: '#000' }).png().toFile(out);
  }
})();
"""
    subprocess.run(["node", "-e", script], input=json.dumps(jobs), text=True, check=True, cwd=ROOT)


def main() -> None:
    icon = icon_svg()
    (STATIC / "favicon.svg").write_text(icon)
    jobs = [(icon, str(STATIC / name), size, size) for name, size in PNG_SIZES.items()]
    jobs.append((og_svg(), str(STATIC / "og.png"), OG_W, OG_H))
    rasterise(jobs)
    print("wrote", ", ".join(["favicon.svg", *PNG_SIZES, "og.png"]))


if __name__ == "__main__":
    main()
