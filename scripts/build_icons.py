#!/usr/bin/env python3
"""Draws the site's icons and share image, in black and white, from the CONTEXT logo.

    python3 scripts/build_icons.py

2026-11-11, at the user's request (the move to timetokyo.pages.dev — "metaや
faviconまでしっかり白黒デザインでTなど使って"); redone 2026-11-13 for the name
CONTEXT ("ロゴやブランド名全てをCONTEXTに変更"):

- Icons: the C of the CONTEXT wordmark ($lib/data/wordmark.ts) in white on
  black. One SVG (static/favicon.svg) and the PNGs browsers and home screens
  ask for — favicon.png 512, apple-touch-icon.png 180, icon-192.png,
  icon-512.png (also the PWA's maskable icon: the C sits well inside its 80%
  safe circle).
- Share image (static/og.png, 1200x630): the whole logo — CONTEXT and the line
  "Aestheticism for Typography" — in white on black, from
  docs/brand/context-logo.svg.

The PNGs are rasterised with sharp (a dependency of the site already) through
Node.
"""

import json
import re
import subprocess
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.svgLib.path import parse_path

ROOT = Path(__file__).resolve().parent.parent
STATIC = ROOT / "static"
LOGO_SVG = ROOT / "docs/brand/context-logo.svg"
WORDMARK_TS = ROOT / "src/lib/data/wordmark.ts"

BLACK = "#000000"
WHITE = "#ffffff"

# Icon
ICON_SIZE = 512
ICON_LETTER_HEIGHT = 0.5  # the C's height as a share of the icon

# Share image
OG_W, OG_H = 1200, 630
OG_MARGIN = 80

PNG_SIZES = {
    "favicon.png": 512,
    "apple-touch-icon.png": 180,
    "icon-192.png": 192,
    "icon-512.png": 512,
}


def icon_svg() -> str:
    source = WORDMARK_TS.read_text()
    d = re.search(r"char: 'C', x0: [\d.]+, x1: [\d.]+, d: '([^']+)'", source).group(1)
    pen = BoundsPen(None)
    parse_path(d, pen)
    x0, y0, x1, y1 = pen.bounds
    height = ICON_SIZE * ICON_LETTER_HEIGHT
    k = height / (y1 - y0)
    tx = (ICON_SIZE - (x1 - x0) * k) / 2 - x0 * k
    ty = (ICON_SIZE - height) / 2 - y0 * k
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {ICON_SIZE} {ICON_SIZE}">\n'
        f"\t<!-- The C of the CONTEXT wordmark, white on black. Generated by\n"
        f"\t     scripts/build_icons.py. -->\n"
        f'\t<rect width="{ICON_SIZE}" height="{ICON_SIZE}" fill="{BLACK}" />\n'
        f'\t<path fill="{WHITE}" transform="translate({tx:.2f} {ty:.2f}) scale({k:.5f})" d="{d}" />\n'
        f"</svg>\n"
    )


def og_svg() -> str:
    """The whole logo (CONTEXT and its line), white on black, centred."""
    svg = LOGO_SVG.read_text()
    view = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', svg)
    lw, lh = float(view.group(1)), float(view.group(2))
    k = (OG_W - 2 * OG_MARGIN) / lw
    tx = OG_MARGIN
    ty = (OG_H - lh * k) / 2
    body = "".join(f'<path d="{d}" />' for d in re.findall(r'<path d="([^"]+)"', svg))
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {OG_W} {OG_H}">'
        f'<rect width="{OG_W}" height="{OG_H}" fill="{BLACK}" />'
        f'<g fill="{WHITE}" transform="translate({tx:.2f} {ty:.2f}) scale({k:.6f})">{body}</g>'
        f"</svg>"
    )


def rasterise(jobs: list[tuple[str, str, int, int]]) -> None:
    """jobs: (svg text, output path, width, height), drawn by sharp."""
    script = """
const sharp = require('sharp');
const jobs = JSON.parse(require('fs').readFileSync(0, 'utf8'));
(async () => {
  for (const [svg, out, w, h] of jobs) {
    await sharp(Buffer.from(svg), { density: 300 }).resize(w, h).flatten({ background: '#000' }).png().toFile(out);
  }
})();
"""
    subprocess.run(["node", "-e", script], input=json.dumps(jobs), text=True, check=True, cwd=ROOT)


def main() -> None:
    icon = icon_svg()
    (STATIC / "favicon.svg").write_text(icon)
    jobs = [(icon, str(STATIC / name), size, size) for name, size in PNG_SIZES.items()]
    jobs.append((og_svg(), str(STATIC / "og.png"), OG_W, OG_H))
    rasterise(jobs)
    print("wrote", ", ".join(["favicon.svg", *PNG_SIZES, "og.png"]))


if __name__ == "__main__":
    main()
