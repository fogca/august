#!/usr/bin/env python3
"""Writes src/lib/data/wordmark.ts from the supplied CONTEXT logo artwork.

    python3 scripts/build_wordmark_from_svg.py

2026-11-13, at the user's request ("ロゴやブランド名全てをTime...からCONTEXTに
変更", with the logo SVG pasted in): the wordmark is no longer set in one of our
faces (scripts/build_wordmark.py did that for "Time Type Tokyo") but is the
artwork itself, docs/brand/context-logo.svg — CONTEXT, with the line
"Aestheticism for Typography" under it.

Only the seven letters of CONTEXT go into wordmark.ts (the Header's lockup and
the opening draw those); the tagline stays in the SVG, for the share image
(scripts/build_icons.py). The letters are the artwork's first seven paths below
the tagline, found by position: the ones whose ink lies above y = TAGLINE_TOP.

Logo.svelte and the Header move the name as two words (see WORDMARK_WORDS), so
CONTEXT is cut into CON and TEXT; on every screen they sit on one line.
"""

import re
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.svgLib.path import parse_path

ROOT = Path(__file__).resolve().parent.parent
SVG = ROOT / "docs/brand/context-logo.svg"
OUT = ROOT / "src/lib/data/wordmark.ts"

WORDMARK_TEXT = "CONTEXT"
LETTERS = list(WORDMARK_TEXT)
# The two words the Header moves: the first CON, then TEXT.
FIRST_WORD_LEN = 3
# The tagline's ink starts well below the letters (y ≈ 180 of 213).
TAGLINE_TOP = 150
DECIMALS = 2


def main() -> None:
    paths = re.findall(r'<path d="([^"]+)"', SVG.read_text())
    letters = []
    for d in paths:
        pen = BoundsPen(None)
        parse_path(d, pen)
        x0, y0, x1, y1 = pen.bounds
        if y1 < TAGLINE_TOP:
            letters.append((x0, y0, x1, y1, d))
    letters.sort(key=lambda l: l[0])
    assert len(letters) == len(LETTERS), f"found {len(letters)} letters"

    width = max(l[2] for l in letters)
    height = max(l[3] for l in letters)
    first, rest = letters[:FIRST_WORD_LEN], letters[FIRST_WORD_LEN:]

    def r(v: float) -> float:
        return round(v, DECIMALS)

    rows = ",\n".join(
        f"\t{{ char: '{c}', x0: {r(l[0])}, x1: {r(l[2])}, d: '{l[4]}' }}"
        for c, l in zip(LETTERS, letters)
    )
    OUT.write_text(
        f"""// GENERATED by scripts/build_wordmark_from_svg.py — edit that, not this.
//
// The wordmark "{WORDMARK_TEXT}", the letters of docs/brand/context-logo.svg,
// one outline per letter in one coordinate space (y down).
// Logo.svelte draws it; $lib/data/logo.ts turns its proportions into the CSS
// custom properties the Header's lockup and the masthead are laid out from.

export const WORDMARK_TEXT = '{WORDMARK_TEXT}';
export const WORDMARK_W = {r(width)};
export const WORDMARK_H = {r(height)};

export interface WordmarkLetter {{
	char: string;
	x0: number;
	x1: number;
	d: string;
}}

/** The two words the Header moves: the letters from..to of WORDMARK_LETTERS,
 *  and the x range of the wordmark they stand on. */
export const WORDMARK_WORDS = [
	{{ text: '{WORDMARK_TEXT[:FIRST_WORD_LEN]}', from: 0, to: {FIRST_WORD_LEN}, x0: 0, x1: {r(first[-1][2])} }},
	{{ text: '{WORDMARK_TEXT[FIRST_WORD_LEN:]}', from: {FIRST_WORD_LEN}, to: {len(LETTERS)}, x0: {r(rest[0][0])}, x1: {r(width)} }}
] as const;

export const WORDMARK_LETTERS: WordmarkLetter[] = [
{rows}
];
"""
    )
    print("wrote", OUT.name, f"{r(width)} x {r(height)}")


if __name__ == "__main__":
    main()
